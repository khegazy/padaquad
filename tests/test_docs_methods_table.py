"""The documentation's methods table matches the method registries.

The table on the methods page is generated by ``docs/_ext/methods_table.py``
from ``UNIFORM_METHODS`` and ``VARIABLE_METHODS``. These tests build it without
Sphinx and check that it has one complete row per registered method, and that
every source it cites is an entry of ``docs/references.bib``.
"""

from __future__ import annotations

import importlib.util
import re
from pathlib import Path

import pytest
import torch

from padaquad import UNIFORM_METHODS, VARIABLE_METHODS
from padaquad.methods import UniformMethodClass, _Tableau

DOCS = Path(__file__).resolve().parents[1] / "docs"


def _table_module():
    spec = importlib.util.spec_from_file_location(
        "methods_table", DOCS / "_ext" / "methods_table.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_one_complete_row_per_registered_method():
    table = _table_module()
    rows = table.methods_table_rows()
    names = [row["name"] for row in rows]
    assert sorted(names) == sorted(set(UNIFORM_METHODS) | set(VARIABLE_METHODS))
    for row in rows:
        method = UNIFORM_METHODS.get(row["name"]) or VARIABLE_METHODS[row["name"]]
        assert row["degree"] == method.degree
        assert row["order"] == method.order
        assert row["estimate_degree"] == method.error_exponent - 2
        assert row["nodes"] == method.n_nodes
        assert row["references"], f"{row['name']} cites no source"
        assert all(str(row[key]) for key, _ in table.COLUMNS), row
    rendered = table.render_methods_table()
    assert len(rendered.strip().splitlines()) == 2 + len(rows)


def test_every_cited_key_is_in_the_bibliography():
    bib_keys = set(
        re.findall(r"^@\w+\{([^,]+),", (DOCS / "references.bib").read_text(), re.M)
    )
    cited = {
        key
        for method in (*UNIFORM_METHODS.values(), *VARIABLE_METHODS.values())
        for key in method.references
    }
    assert cited <= bib_keys, f"keys missing from references.bib: {cited - bib_keys}"


@pytest.mark.parametrize(
    "references", [["gonnet2012"], ("gonnet2012", 3), "gonnet2012"]
)
def test_references_must_be_a_tuple_of_str(references):
    c = torch.tensor([0.0, 1.0], dtype=torch.float64)
    with pytest.raises(ValueError, match="references"):
        UniformMethodClass(
            degree=1,
            error_exponent=2,
            tableau=_Tableau(c=c, b=c * 0 + 0.5, b_error=c * 0),
            references=references,
        )
